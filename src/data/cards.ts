let alcoholReplacementIndex = 0
const afterdarkCards = afterdarkBaseCards.map((card) => {
  if (!card.alcohol || !card.sexualAction) return card
  const index = alcoholReplacementIndex % alcoholOnlyDares.length
  alcoholReplacementIndex += 1
  return {
    ...card,
    text: alcoholOnlyDares[index],
    theme: `alcohol-only-${index + 1}`,
    mechanic: 'direct' as const,
    sexualAction: false,
  }
})

