import { authored, authoredDeck } from './factory'
import type { CardInteraction, CardMechanic, Heat, TruthPurpose } from '../types'

type Entry = { text: string; minPlayers?: number; alcohol?: boolean; duration?: 'temporary'; pairing?: 'none' | 'any' | 'mutual-close' }
const truthThemes = ['party', 'alcohol', 'awkward', 'exes', 'secrets', 'flirt', 'chaos', 'regret', 'night', 'embarrassment']
const truthMechanics: CardMechanic[] = ['story', 'confession', 'choice', 'experience']
const truthInteractions: CardInteraction[] = ['conversation', 'confession', 'humor', 'social-choice', 'flirt']
const purposes: TruthPurpose[] = ['story', 'confession', 'choice', 'experience', 'curiosity']
const dareThemes = ['clothing', 'rules', 'alcohol', 'dance', 'awkward', 'pair', 'chaos', 'flirt', 'embarrassment', 'night']
const dareMechanics: CardMechanic[] = ['direct', 'timed', 'partner-choice', 'group', 'clothing']
const dareInteractions: CardInteraction[] = ['clothing', 'humor', 'alcohol', 'group-reaction', 'flirt', 'embarrassment']

function truthDeck(heat: Heat, entries: Entry[]) {
  return authoredDeck({
    scenario: 'afterdark', heat, type: 'truth',
    cards: entries.map((entry, index) => authored(entry.text, truthThemes[index % truthThemes.length], `afterdark-${heat}-truth-${index + 1}`, truthMechanics[index % truthMechanics.length], truthInteractions[index % truthInteractions.length], {
      purpose: purposes[index % purposes.length],
      requiresTarget: false,
      pairing: 'none',
      minPlayers: entry.minPlayers,
      alcohol: entry.alcohol,
    })),
  })
}

function dareDeck(heat: Heat, entries: Entry[]) {
  return authoredDeck({
    scenario: 'afterdark', heat, type: 'dare',
    cards: entries.map((entry, index) => authored(entry.text, dareThemes[index % dareThemes.length], `afterdark-${heat}-dare-${index + 1}`, dareMechanics[index % dareMechanics.length], dareInteractions[index % dareInteractions.length], {
      pairing: entry.pairing ?? 'none',
      requiresTarget: (entry.pairing ?? 'none') === 'none' ? false : undefined,
      minPlayers: entry.minPlayers,
      alcohol: entry.alcohol,
      duration: entry.duration,
    })),
  })
}

