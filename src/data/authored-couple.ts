import { authored, authoredDeck } from './factory'
import type { CardInteraction, CardMechanic, Heat, TruthPurpose } from '../types'

const truthThemes = ['habits', 'memories', 'care', 'humor', 'connection', 'conflict', 'boundaries', 'future', 'trust', 'affection']
const truthMechanics: CardMechanic[] = ['story', 'confession', 'choice', 'compatibility']
const truthInteractions: CardInteraction[] = ['conversation', 'confession', 'humor', 'flirt']
const truthPurposes: TruthPurpose[] = ['story', 'confession', 'choice', 'compatibility', 'curiosity', 'values']
const dareThemes = ['humor', 'memories', 'touch', 'music', 'photos', 'care', 'flirt', 'creativity', 'closeness', 'everyday']
const dareMechanics: CardMechanic[] = ['direct', 'timed', 'partner-choice', 'physical']
const dareInteractions: CardInteraction[] = ['humor', 'physical', 'flirt', 'conversation']

function truthDeck(heat: Heat, texts: string[]) {
  return authoredDeck({
    scenario: 'couple', heat, type: 'truth',
    cards: texts.map((text, index) => authored(
      text,
      truthThemes[index % truthThemes.length],
      `couple-${heat}-truth-${index + 1}`,
      truthMechanics[index % truthMechanics.length],
      truthInteractions[index % truthInteractions.length],
      { purpose: truthPurposes[index % truthPurposes.length], requiresTarget: false, pairing: 'none' },
    )),
  })
}

function dareDeck(heat: Heat, texts: string[]) {
  return authoredDeck({
    scenario: 'couple', heat, type: 'dare',
    cards: texts.map((text, index) => authored(
      text,
      dareThemes[index % dareThemes.length],
      `couple-${heat}-dare-${index + 1}`,
      dareMechanics[index % dareMechanics.length],
      dareInteractions[index % dareInteractions.length],
      { pairing: 'any' },
    )),
  })
}

